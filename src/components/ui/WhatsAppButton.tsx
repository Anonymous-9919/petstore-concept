"use client";

import { useEffect, useState } from "react";
import { useLanguageStore } from "@/lib/store";

export function WhatsAppButton() {
  const lang = useLanguageStore((s) => s.lang);
  const [whatsappData, setWhatsappData] = useState<{
    href: string;
    message: string;
  } | null>(null);

  useEffect(() => {
    import("@/data/whatsapp.json").then((mod) => {
      const data = mod.default;
      setWhatsappData({
        href: data.href,
        message: lang === "ar" ? data.message_ar : data.message_en,
      });
    });
  }, [lang]);

  if (!whatsappData) return null;

  const whatsappUrl = `${whatsappData.href}?text=${encodeURIComponent(whatsappData.message)}`;

  return (
    <a
      href={whatsappUrl}
      target="_blank"
      rel="noopener noreferrer"
      className="whatsapp-float animate-pulse"
      aria-label="WhatsApp"
    >
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width="32"
        height="32"
        viewBox="0 0 24 24"
        fill="white"
      >
        <path d="M12.04 2.01C6.49 2.01 2 6.46 2 12c0 1.98.51 3.9 1.46 5.63l-1.45 5.33c-.11.38.26.77.66.69l5.33-1.45c1.62.92 3.54 1.47 5.53 1.47 5.55 0 10.04-4.5 10.04-10.01S17.59 2.01 12.04 2.01zm5.74 13.14c-.34.97-2.02 1.78-3.26 2.04-.29.07-.61.11-.92.11-.24 0-.51-.05-.76-.12-.34-.08-4.59-1.57-5.34-2.02-.02 0 .29-.35.99-1.05.52-.51 2.03-1.95 2.6-2.49s.56-.37.73-.31c.18.07.35.34.62.53.27.2 1.75 1.01 2.14 1.22.38.21.58.26.84.16.26-.09.42-1.74.5-2.18.08-.44.1-1.04 0-1.45-.09-.34-.44-1.02-.9-1.25-.25-.12-1.31-.67-1.27-.67-1.12-.39-1.94-9.55-2.08-10.5s-.06-1.74-.02-1.95c.05-.22 1.32 1.01 2.62 2.99.16.25.34.52.6.85.26.34 2.12 2.66 2.97 3.58.86.92 1.42 1.32 1.82 1.32.22 0 1.06-.7 1.06-1.47 0-.22-.01-.44-.01-.44s-.08-1.42-.22-2.2-.23-1.36-.28-1.47c-.05-.13-.43-1.03-1.01-1.15-.57-.13-1.26-.11-1.93-.05-1.38.13-2.12.33-2.16.33-.69 0-.79-.13-1.14-1.12-.22-.65-.6-2.38-1.04-4.16C6.12 3.47 3.99 7.59 3.97 11.15c0 3.66 2.29 6.83 5.55 8.03 1.36.49 2.83.75 4.37.75 1.54 0 3.01-.26 4.37-.76 3.26-1.2 5.55-4.37 5.59-8.03 0-3.76-2.42-6.98-5.84-8.13-1.27-.39-2.5-.6-3.63-.6-1.14 0-2.36.21-3.64.63.19-.17.37-.33.55-.49 7.29-7.04 1.97-20.04-5.61-17.85-2.32 1.93-1.47 6.81.9 11.53C3.3 8.99 2 9.04 2 11.99c0 .25 0 .51.01.77-2.09-3.29-1.81-6.07-1.13-8.83-.25-.04-.49-.07-.74-.09 0 1.04.02 1.85.02 2.38 0 4.42.33 5.75 1.31 8.18-.13.05-.26.09-.39.14-2.37-.74-4.22-2.13-5.23-3.94-2.13 2.54-2.89 5.86-1.96 9.01.53 1.9 1.45 3.64 2.69 5.13-2.12 1.44-4.64 2.24-7.42 2.24-.42 0-.83-.02-1.24-.06 3.29 3.15 7.76 4.8 12.58 4.8 6.59 0 11.99-5.41 11.99-12 0-3.15-1.25-6.06-3.28-8.17l.11-.11c-1.38 0-2.73-.36-3.95-1.03-3.54 2.62-4.02 7.49-1.14 10.92.36.45.76.87 1.2 1.27.61-.53 1.28-.94 2-1.2.06-.07.11-.13.16-.2 0-1.02 0-1.99-.01-2.3z" />
        <path d="M10.59 8.54c-.48 0-.87.38-.87.85s.39.85.87.85c.48 0 .87-.38.87-.85s-.39-.85-.87-.85zm3.82 0c-.48 0-.87.38-.87.85s.39.85.87.85c.48 0 .87-.38.87-.85s-.39-.85-.87-.85z" />
      </svg>
    </a>
  );
}
